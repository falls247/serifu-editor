import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)('playwright');
const port=5224,server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:String(port)},stdio:['ignore','pipe','inherit']});
let browser;
try{
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('exit',code=>reject(new Error('server exited '+code)));server.once('error',reject);});
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:960},acceptDownloads:true});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:'+port);
  await page.uncheck('#autosaveEnabled');
  const content=await page.evaluate(()=>{
    const c=document.createElement('canvas');c.width=800;c.height=600;c.getContext('2d').fillRect(0,0,800,600);return c.toDataURL().split(',')[1];
  });
  await page.locator('#fileInput').setInputFiles({name:'lettering.png',mimeType:'image/png',buffer:Buffer.from(content,'base64')});
  await page.waitForFunction(()=>document.querySelector('.image-row')&&!document.querySelector('#projectLoad').disabled);
  const row=page.locator('.image-row').first();await row.locator('[data-action=add-sfx]').click();
  const card=row.locator('[data-kind=sfx]');
  await card.locator('textarea[data-field=text]').fill('ザーーーーッ');
  await card.locator('[data-action=sfx-glyph-enter]').click();
  assert.equal(await card.locator('[data-glyph-index]').count(),6);
  await card.locator('[data-glyph-field=dx]').fill('35');
  await card.locator('[data-glyph-field=dx]').press('Tab');
  assert.equal(await card.locator('[data-glyph-field=dx]').inputValue(),'35');
  await card.locator('[data-glyph-index="5"]').click();
  await card.locator('[data-glyph-field=rotation]').fill('16');
  await card.locator('[data-glyph-field=rotation]').press('Tab');
  await card.locator('textarea[data-field=text]').fill('ボーーーーーッ');
  await card.locator('[data-action=sfx-glyph-select]').first().click();
  assert.equal(await card.locator('[data-glyph-index]').count(),7);
  await card.locator('[data-glyph-inherit]').selectOption('character');
  await card.locator('textarea[data-field=text]').fill('ボコッ');
  await card.locator('[data-action=sfx-glyph-select]').first().click();
  assert.equal(await card.locator('[data-glyph-index]').count(),3);
  await row.locator('[data-action=undo]').click();
  assert.equal(await card.locator('[data-glyph-index]').count(),7);
  await row.locator('[data-action=redo]').click();
  assert.equal(await card.locator('[data-glyph-index]').count(),3);
  await card.locator('textarea[data-field=text]').fill('ザーーーーッ');
  await card.locator('[data-action=sfx-glyph-select]').first().click();
  await card.locator('[data-glyph-stroke-shape]').selectOption('s');
  await card.locator('[data-glyph-stroke-width=start]').fill('32');
  await card.locator('[data-glyph-stroke-width=start]').press('Tab');
  await page.selectOption('#projectFormat','json');
  const dl=page.waitForEvent('download');await page.click('#projectSave');const download=await dl;
  const project=JSON.parse(await readFile(await download.path(),'utf8'));
  const layer=project.pages[0].layers.find(l=>l.kind==='sfx');
  assert.equal(project.version,14);assert.equal(layer.text,'ザーーーーッ');
  assert.equal(layer.lettering.strokes[0].shape,'s');
  assert.equal(layer.lettering.strokes[0].widths[0].w,32);
  assert.deepEqual(errors,[]);
  console.log('SFX glyph + stroke editor browser smoke PASS');
}finally{await browser?.close();server.kill('SIGTERM');}
